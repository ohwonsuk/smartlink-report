-- 데이터 확인 (운전자별 안전점수)
SELECT 
  c.cmny_nm as "고객사명",
  ss.driver_name as "운전자",
  ss.department as "소속",
  ss.employee_no as "사번",
  ss.trip_count as "운행건수",
  ss.total_distance_km as "운행거리(km)",
  ss.total_driving_minutes as "운행시간(분)",
  ss.sudden_accel_count as "급가속횟수",
  ss.sudden_decel_count as "급감속횟수",
  ss.avg_overspeed_rate as "평균과속률",
  ss.avg_safety_score as "평균안전점수"
FROM public.safety_scores ss
JOIN public.companies c ON ss.cmny_id = c.cmny_id
WHERE ss.year_month = '202511'
ORDER BY ss.cmny_id, ss.total_distance_km DESC;

