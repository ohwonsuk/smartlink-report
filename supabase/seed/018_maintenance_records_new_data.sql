-- 데이터 확인 (정비현황)
SELECT 
  c.cmny_nm as "고객사명",
  mr.maintenance_type as "구분",
  mr.vehicle_no as "차량번호",
  mr.vehicle_model as "모델",
  mr.mileage_km as "주행거리",
  mr.check_in_date as "입고일자",
  mr.check_out_date as "출고일자",
  COALESCE(mr.service_product, '') as "정비상품",
  mr.service_center as "정비소명",
  mr.status as "완료상태",
  TO_CHAR(mr.created_at, 'YYYY-MM-DD HH24:MI') as "등록일",
  TO_CHAR(mr.updated_at, 'YYYY-MM-DD HH24:MI') as "수정일"
FROM public.maintenance_records mr
JOIN public.companies c ON mr.cmny_id = c.cmny_id
WHERE mr.year_month = '202511'
ORDER BY mr.check_in_date DESC;

