  cmny_nm as "고객사명",
  year_month as "년월",
  vehicle_no as "차량번호",
  vehicle_model as "차종",
  period_start as "기간시작",
  period_end as "기간종료",
  total_distance_km as "총주행거리(km)",
  total_commute_km as "출퇴근용거리(km)",
  total_business_km as "업무용거리(km)",
  total_work_usage_km as "업무용사용거리(km)",
  business_usage_pct as "업무용사용비율(%)",
  log_count as "운행일수"
FROM public.driving_logs_monthly_summary
WHERE year_month = '202511'
ORDER BY cmny_id, total_distance_km DESC;

