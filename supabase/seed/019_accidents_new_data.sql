SELECT 
  c.cmny_nm as "고객사명",
  a.department as "소속",
  a.driver_name as "운전자명",
  a.vehicle_no as "차량번호",
  a.vehicle_model as "차종",
  a.accident_type as "사고구분",
  a.accident_category as "사고분류",
  TO_CHAR(a.accident_date_time, 'YYYY-MM-DD HH24:MI') as "사고일시",
  a.reception_date as "접수일자",
  a.reception_no as "접수번호",
  a.status as "처리상태",
  a.completion_date as "종결일자",
  a.deductible as "면책금",
  a.location as "사고장소"
FROM public.accidents a
JOIN public.companies c ON a.cmny_id = c.cmny_id
WHERE a.year_month = '202512'
ORDER BY a.accident_date_time DESC;
