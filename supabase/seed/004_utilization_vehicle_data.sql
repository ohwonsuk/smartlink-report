SELECT 
  c.cmny_nm,
  uv.year_month,
  uv.vehicle_no,
  uv.utilization_pct,
  (uv.utilization_pct * 3) as utilization_pct_8h
FROM public.utilization_vehicle uv
JOIN public.companies c ON uv.cmny_id = c.cmny_id
WHERE uv.year_month = '202511'
ORDER BY c.cmny_nm, uv.utilization_pct DESC;



