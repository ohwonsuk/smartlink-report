  c.cmny_nm,
  uv.vehicle_no,
  uv.vehicle_model,
  uv.utilization_pct,
  uv.driving_minutes
FROM public.utilization_vehicle uv
JOIN public.companies c ON uv.cmny_id = c.cmny_id
WHERE uv.year_month = '202511'
ORDER BY uv.cmny_id, uv.utilization_pct DESC;

